"""HTML widget toolkit + page shell. Stats compose these; CSS lives here once."""
from __future__ import annotations

import html

from .util import WDL


def esc(x) -> str:
    return html.escape(str(x))


def pct(n: float, total: float) -> str:
    return f"{100 * n / total:.0f}%" if total else "—"


def card(big, label: str) -> str:
    return f'<div class="card"><div class="big">{esc(big)}</div><div class="lbl">{esc(label)}</div></div>'


def cards(items: list[tuple]) -> str:
    """items: list of (big, label)."""
    return '<div class="cards">' + "".join(card(b, l) for b, l in items) + "</div>"


def bar(w: int, d: int, l: int) -> str:
    """Win/draw/loss proportion bar."""
    total = w + d + l
    if not total:
        return ""
    pw, pd, pl = (100 * x / total for x in (w, d, l))
    return (
        '<div class="bar">'
        f'<span class="w" style="width:{pw}%"></span>'
        f'<span class="d" style="width:{pd}%"></span>'
        f'<span class="l" style="width:{pl}%"></span>'
        "</div>"
    )


def table(headers: list[str], rows: list[list]) -> str:
    head = "".join(f"<th>{esc(h)}</th>" for h in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>" for row in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def wdl_table(label_col: str, groups: dict, sort=True, limit=None) -> str:
    """Standard W/D/L table from a {label: WDL} dict (e.g. from util.tally)."""
    items = list(groups.items())
    if sort:
        items.sort(key=lambda kv: -kv[1].total)
    if limit:
        items = items[:limit]
    rows = []
    for label, x in items:
        rows.append([
            esc(label), x.total, x.win, x.draw, x.loss,
            pct(x.win, x.total), bar(x.win, x.draw, x.loss),
        ])
    return table([label_col, "Games", "W", "D", "L", "Win%", ""], rows)


def sparkline(values: list[float], color_var="--w") -> str:
    if len(values) < 2:
        return ""
    lo, hi = min(values), max(values)
    rng = (hi - lo) or 1
    pts = " ".join(
        f"{100 * i / (len(values) - 1):.1f},{100 - 100 * (v - lo) / rng:.1f}"
        for i, v in enumerate(values)
    )
    return (
        f'<svg viewBox="0 0 100 100" preserveAspectRatio="none" class="spark">'
        f'<polyline points="{pts}" style="stroke:var({color_var})"/></svg>'
    )


